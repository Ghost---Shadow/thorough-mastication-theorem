"""Make docs/theorem-table.md: every theorem of the squiggly line library, with a verdict.

The first two columns (the theorem and what it says) are read from the Lean sources of the
library by its own search tool, so a theorem added there shows up here on the next run. The
last two columns (does it help, and why) are written by hand in docs/verdicts.json. A
theorem with no verdict of its own takes the verdict of its file, and a theorem in a file
with no verdict is marked "not judged".

    python scripts/make_theorem_table.py --write     # rewrite the page
    python scripts/make_theorem_table.py --check     # fail if the page is out of date

The library is looked for in --library, then in the variable SQUIGGLY_LINE_REPO, then next
to this repository (../squiggly-line-theorem or ../squiggly-line-conjecture).
"""

import argparse
import json
import os
import subprocess
import sys
from collections import Counter
from pathlib import Path

HERE = Path(__file__).resolve().parent.parent
PAGE = HERE / "docs" / "theorem-table.md"
VERDICTS = HERE / "docs" / "verdicts.json"
LIBRARY_URL = "https://github.com/Ghost---Shadow/squiggly-line-theorem"
PREFIX = "lean/SquigglyLine/"
NOT_JUDGED = ["not judged", "New since the last pass. Nobody has looked at it yet."]


def find_library(given: str | None) -> Path:
    candidates = [given, os.environ.get("SQUIGGLY_LINE_REPO"),
                  HERE.parent / "squiggly-line-theorem", HERE.parent / "squiggly-line-conjecture"]
    for candidate in candidates:
        if candidate and (Path(candidate) / "scripts" / "find_theorem.py").exists():
            return Path(candidate).resolve()
    sys.exit("The squiggly line library was not found. Pass --library PATH.")


def read_theorems(library: Path) -> list[dict]:
    """Every theorem of the library, in the order of its files."""
    sys.path.insert(0, str(library / "scripts"))
    os.chdir(library)
    import find_theorem

    index = find_theorem.build_index()
    theorems = []
    for declaration in index.declarations:
        if not declaration.is_theorem:
            continue
        theorems.append({
            "name": declaration.display,
            "short": declaration.name,
            "path": declaration.path,
            "file": declaration.path[len(PREFIX):-len(".lean")],
            "says": find_theorem.first_sentence(declaration.doc, 120),
        })
    return sorted(theorems, key=lambda theorem: theorem["path"])


def read_commit(library: Path) -> str:
    result = subprocess.run(["git", "-C", str(library), "rev-parse", "--short", "HEAD"],
                            capture_output=True, text=True)
    return result.stdout.strip() or "unknown"


def judge(theorem: dict, verdicts: dict) -> list[str]:
    """The verdict of a theorem: its own, else its file's, else its folder's."""
    for key in (theorem["name"], theorem["short"]):
        if key in verdicts["theorems"]:
            return verdicts["theorems"][key]
    folder_verdict = None
    for group in verdicts["groups"]:
        for pattern in group["files"]:
            if pattern == theorem["file"]:
                return [group["helps"], group["why"]]
            if pattern.endswith("/*") and theorem["file"].startswith(pattern[:-1]) and folder_verdict is None:
                folder_verdict = [group["helps"], group["why"]]
    return folder_verdict or NOT_JUDGED


def find_stale(theorems: list[dict], verdicts: dict) -> list[str]:
    """Names in the verdicts that the library no longer has."""
    known = {theorem["name"] for theorem in theorems} | {theorem["short"] for theorem in theorems}
    return sorted(name for name in verdicts["theorems"] if name not in known)


def clean_cell(text: str) -> str:
    return text.replace("|", "\\|").replace("\n", " ")


def make_page(theorems: list[dict], verdicts: dict, commit: str) -> str:
    judged = [(theorem, judge(theorem, verdicts)) for theorem in theorems]
    counts = Counter(verdict[0] for _, verdict in judged)
    lines = [
        "# Does it help? Every theorem of the squiggly line library",
        "",
        "Generated by `python scripts/make_theorem_table.py --write`. Do not edit this page by",
        "hand: the theorem and what it says are read from the library, and the verdicts are in",
        "`docs/verdicts.json`.",
        "",
        f"Library: [squiggly-line-theorem]({LIBRARY_URL}) at commit `{commit}`, {len(theorems)} theorems.",
        "",
        "The question for each row: does this theorem help to say what happens when a batch is",
        "trained to convergence before the next one is drawn?",
        "",
        "| Verdict | Theorems |",
        "|---|---|",
    ]
    for verdict in ["yes", "partly", "no", "not judged"]:
        lines.append(f"| {verdict} | {counts.get(verdict, 0)} |")
    lines += [
        "",
        "A reason that starts with \"File:\" was given to the whole file from its subject. The",
        "theorem itself was not read for that row. A reason without it was written for that",
        "theorem. \"Not judged\" marks a theorem that nobody has looked at yet.",
        "",
        "## The rows that help",
        "",
        "| Theorem | What it says | Helps | Why |",
        "|---|---|---|---|",
    ]
    for theorem, verdict in judged:
        if verdict[0] == "yes":
            lines.append(make_row(theorem, verdict))
    current_file = None
    lines += ["", "## Every theorem, by file"]
    for theorem, verdict in judged:
        if theorem["file"] != current_file:
            current_file = theorem["file"]
            lines += ["", f"### {current_file}", "",
                      "| Theorem | What it says | Helps | Why |", "|---|---|---|---|"]
        lines.append(make_row(theorem, verdict))
    return "\n".join(lines) + "\n"


def make_row(theorem: dict, verdict: list[str]) -> str:
    link = f"[`{theorem['name']}`]({LIBRARY_URL}/blob/main/{theorem['path']})"
    return f"| {link} | {clean_cell(theorem['says'])} | {verdict[0]} | {clean_cell(verdict[1])} |"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    parser.add_argument("--library", help="path to a checkout of the squiggly line library")
    parser.add_argument("--write", action="store_true", help="rewrite the page")
    parser.add_argument("--check", action="store_true", help="fail if the page is out of date")
    args = parser.parse_args()

    library = find_library(args.library)
    verdicts = json.loads(VERDICTS.read_text(encoding="utf-8"))
    theorems = read_theorems(library)
    page = make_page(theorems, verdicts, read_commit(library))
    stale = find_stale(theorems, verdicts)
    for name in stale:
        print(f"verdicts.json names a theorem the library does not have: {name}", file=sys.stderr)

    counts = Counter(judge(theorem, verdicts)[0] for theorem in theorems)
    print(f"theorems: {len(theorems)}  " + "  ".join(f"{key}: {counts[key]}" for key in sorted(counts)))
    if args.write:
        PAGE.write_text(page, encoding="utf-8", newline="\n")
        print(f"wrote {PAGE.relative_to(HERE).as_posix()}")
    if args.check and (not PAGE.exists() or PAGE.read_text(encoding="utf-8") != page):
        print("docs/theorem-table.md is out of date. Run with --write.", file=sys.stderr)
        return 1
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
